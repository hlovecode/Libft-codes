#include "libft.h"

// 从 s 指向的内存地址开始，把连续的 n 个字符全部设置为0
void	ft_bzero(void *s, size_t n)
{
	unsigned char *p;

	p = (unsigned char *)s;
	while (n > 0)
	{
		*p = 0;
		p++;
		n--;
	}
}
